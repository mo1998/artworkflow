#!/usr/bin/env python3
"""Build the README gallery from approved assets.

The gallery is how someone evaluates the pipeline without a GPU and a 17 GB checkpoint, so it is
generated by a script rather than hand-assembled: re-run it after a batch and the images match the
current asset set.

    python3 scripts/make_gallery.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parent / "lib")]

from lib.common import ROOT, ensure_inside_project  # noqa: E402
from lib.imageops import flatten_on, open_image  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

GALLERY = ROOT / "docs" / "gallery"
BACKGROUND = (232, 232, 238)
LABEL_HEIGHT = 26


def _tile(paths: list[tuple[str, Path]], *, background=BACKGROUND) -> Image.Image:
    images = [(label, open_image(path)) for label, path in paths if path.exists()]
    if not images:
        raise SystemExit("no images to compose; run the pipeline first")
    width = sum(img.width for _, img in images)
    height = max(img.height for _, img in images) + LABEL_HEIGHT
    sheet = Image.new("RGB", (width, height), background)
    draw = ImageDraw.Draw(sheet)
    x = 0
    for label, img in images:
        sheet.paste(flatten_on(img, background), (x, LABEL_HEIGHT))
        draw.text((x + 8, 8), label, fill=(18, 18, 24))
        x += img.width
    return sheet


def _stack(rows: list[Image.Image], *, background=BACKGROUND) -> Image.Image:
    width = max(row.width for row in rows)
    height = sum(row.height for row in rows)
    sheet = Image.new("RGB", (width, height), background)
    y = 0
    for row in rows:
        sheet.paste(row, (0, y))
        y += row.height
    return sheet


def _save(image: Image.Image, name: str, *, max_width: int = 2400) -> Path:
    if image.width > max_width:
        scale = max_width / image.width
        image = image.resize((max_width, round(image.height * scale)), Image.LANCZOS)
    GALLERY.mkdir(parents=True, exist_ok=True)
    dest = ensure_inside_project(GALLERY / name, what="gallery output")
    image.save(dest, "PNG", optimize=True)
    print(f"{name:28s} {image.width}x{image.height}  {dest.stat().st_size // 1024} KB")
    return dest


def approved(*parts: str) -> Path:
    return ROOT / "assets" / "approved" / Path(*parts)


def processed(run_key: str, frame: int) -> Path:
    return ROOT / "assets" / "processed" / run_key / f"frame_{frame:04d}.png"


def main() -> None:
    painted = _tile([
        ("vampire_manor_house", approved("buildings", "vampire_manor_house.png")),
        ("vampire_crypt", approved("buildings", "vampire_crypt.png")),
        ("vampire_blood_well", approved("props", "vampire_blood_well.png")),
        ("vampire_lord", approved("portraits", "vampire_lord.png")),
    ])
    procedural = _tile([
        ("vampire_keep", approved("buildings", "vampire_keep.png")),
        ("vampire_keep__lvl2", approved("buildings", "vampire_keep__lvl2.png")),
        ("vampire_keep__lvl3", approved("buildings", "vampire_keep__lvl3.png")),
        ("vampire_grave", approved("props", "vampire_grave.png")),
    ])
    _save(_stack([painted, procedural]), "vampire-set.png")

    _save(_stack([
        _tile([
            ("demo_watchtower_a", approved("buildings", "demo_watchtower_a.png")),
            ("demo_watchtower_b", approved("buildings", "demo_watchtower_b.png")),
            ("demo_hut", approved("buildings", "demo_hut.png")),
            ("demo_hut__lvl3", approved("buildings", "demo_hut__lvl3.png")),
        ]),
        _tile([
            ("demo_hut_flag", processed("demo_hut_flag", 0)),
            ("vampire_gate_torch", processed("vampire_gate_torch", 0)),
            ("vampire_gate_torch (flicker peak)", processed("vampire_gate_torch", 8)),
            ("vampire_watcher (turntable)", processed("vampire_watcher", 6)),
            ("vampire_watcher (turntable)", processed("vampire_watcher", 18)),
        ]),
    ]), "demo-set.png")

    # Tiers side by side with the shared ground line drawn in, because that is the claim.
    tiers = _tile([
        ("keep L1", approved("buildings", "vampire_keep.png")),
        ("keep L2", approved("buildings", "vampire_keep__lvl2.png")),
        ("keep L3", approved("buildings", "vampire_keep__lvl3.png")),
        ("hut L1", approved("buildings", "demo_hut.png")),
        ("hut L2", approved("buildings", "demo_hut__lvl2.png")),
        ("hut L3", approved("buildings", "demo_hut__lvl3.png")),
    ])
    draw = ImageDraw.Draw(tiers)
    row = tiers.height - 1
    draw.line([(0, row), (tiers.width, row)], fill=(200, 30, 40), width=2)
    draw.text((8, row - 16), "all tiers share this ground line (canvas row 499 of 512)", fill=(150, 20, 30))
    _save(tiers, "upgrade-tiers.png")


if __name__ == "__main__":
    main()
